"""Local OpenBao server lifecycle (§07 order 3): generated config, detached start, pid, stop.

Config (verified against OpenBao 2.7.1, ADR-0042): single-node integrated storage (``raft``) under
``<data dir>/openbao/raft`` — the legacy ``file`` backend is no longer available ("unknown storage
type file") and ``disable_mlock`` is no longer a supported field, so neither is written. TCP
listener bound to the loopback address from ``settings.openbao_addr`` with TLS disabled (loopback
only, V1 §06); ``cluster_addr`` on the next loopback port; UI disabled. No secrets in the config.
"""

from __future__ import annotations

import json
import subprocess
import sys
import time
from pathlib import Path
from typing import Any
from urllib.parse import urlsplit

import psutil

from aeos.core.binaries import BinaryLookup, locate_binary
from aeos.core.config import Settings
from aeos.secrets.openbao import LOOPBACK, OpenBaoUnavailable


def server_dir(settings: Settings) -> Path:
    return settings.data_dir / "openbao"


def pid_file(settings: Settings) -> Path:
    return server_dir(settings) / "bao.pid.json"


def log_file(settings: Settings) -> Path:
    return settings.layout.logs / "openbao.log"


def bin_lookup(settings: Settings) -> BinaryLookup:
    """The OpenBao binary by the one rule the reconciler and the Doctor also use (``aeos.core.binaries``); on a miss
    ``lookup`` / ``rejected`` say which step decided (an unusable ``openbao_binary`` setting is authoritative)."""
    return locate_binary("bao", configured=settings.openbao_binary, data_dir=settings.data_dir)


def bin_path(settings: Settings) -> Path | None:
    found = bin_lookup(settings).path
    return Path(found) if found else None


def _host_port(settings: Settings) -> tuple[str, int]:
    parts = urlsplit(settings.openbao_addr)
    host = parts.hostname or ""
    if host not in LOOPBACK:
        raise OpenBaoUnavailable(f"OpenBao must listen on loopback only, got {host!r}")
    if parts.scheme != "http":
        raise OpenBaoUnavailable("the generated local config serves plain HTTP on loopback; use http://127.0.0.1:<port>")
    return ("127.0.0.1" if host == "localhost" else host), parts.port or 8200


def _fmt(host: str, port: int) -> str:
    return f"[{host}]:{port}" if ":" in host else f"{host}:{port}"


def listener_address(settings: Settings) -> str:
    return _fmt(*_host_port(settings))


def config_text(settings: Settings) -> str:
    host, port = _host_port(settings)
    storage = (server_dir(settings) / "raft").as_posix()
    return "\n".join([
        "# Generated by DLY AEOS (aeos vault start). Loopback only; no secrets in this file.",
        f'storage "raft" {{\n  path    = "{storage}"\n  node_id = "aeos-local"\n}}',
        f'listener "tcp" {{\n  address         = "{_fmt(host, port)}"\n'
        f'  cluster_address = "{_fmt(host, port + 1)}"\n  tls_disable     = true\n}}',
        f'api_addr = "http://{_fmt(host, port)}"',
        f'cluster_addr = "https://{_fmt(host, port + 1)}"',
        "ui = false",
        "",
    ])


def write_config(settings: Settings) -> Path:
    d = server_dir(settings)
    (d / "raft").mkdir(parents=True, exist_ok=True)
    path = d / "config.hcl"
    path.write_text(config_text(settings), encoding="utf-8")
    return path


def running(settings: Settings) -> dict[str, Any] | None:
    try:
        info = json.loads(pid_file(settings).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None
    try:
        p = psutil.Process(int(info["pid"]))
        alive = p.is_running() and abs(p.create_time() - float(info.get("create_time", 0))) < 2.0
    except (psutil.Error, KeyError, ValueError, TypeError):
        alive = False
    info["alive"] = alive
    return info


def bao_version(binary: Path) -> str | None:
    kwargs: dict[str, Any] = {}
    if sys.platform == "win32":
        kwargs["creationflags"] = getattr(subprocess, "CREATE_NO_WINDOW", 0)
    try:
        out = subprocess.run([str(binary), "version"], capture_output=True, text=True, timeout=20, check=False,
                             stdin=subprocess.DEVNULL, env=_server_env(), **kwargs).stdout
    except (OSError, subprocess.SubprocessError):
        return None
    for tok in out.split():
        if tok.lstrip("v")[:1].isdigit():
            return tok.lstrip("v")
    return None


def _server_env() -> dict[str, str]:
    from aeos.claude_bridge.env import child_env

    return child_env()  # same allow-list: no AEOS/BAO/VAULT/provider variables reach the server


def start(settings: Settings, binary: Path) -> dict[str, Any]:
    cur = running(settings)
    if cur and cur.get("alive"):
        return {**cur, "already_running": True}
    cfg = write_config(settings)
    log_path = log_file(settings)
    log_path.parent.mkdir(parents=True, exist_ok=True)
    kwargs: dict[str, Any] = {}
    if sys.platform == "win32":
        kwargs["creationflags"] = (getattr(subprocess, "DETACHED_PROCESS", 0) | getattr(subprocess, "CREATE_NEW_PROCESS_GROUP", 0)
                                   | getattr(subprocess, "CREATE_NO_WINDOW", 0))
    else:
        kwargs["start_new_session"] = True
    with log_path.open("ab") as logf:
        proc = subprocess.Popen([str(binary), "server", f"-config={cfg}"], stdout=logf, stderr=subprocess.STDOUT,
                                stdin=subprocess.DEVNULL, cwd=str(server_dir(settings)), env=_server_env(), **kwargs)
    try:
        ctime = psutil.Process(proc.pid).create_time()
    except psutil.Error:
        ctime = time.time()
    info = {"pid": proc.pid, "create_time": ctime, "addr": settings.openbao_addr, "config": str(cfg),
            "log": str(log_path), "started_at": time.time()}
    pid_file(settings).write_text(json.dumps(info), encoding="utf-8")
    _store_changed("OpenBao started", "started")
    return info


def _store_changed(reason: str, transition: str) -> None:
    from aeos.secrets.readiness import store_state_changed

    # checks that saw the store down (or up) re-run; never raises
    store_state_changed(reason, transition=transition)


def stop(settings: Settings, *, timeout: float = 10.0) -> bool:
    info = running(settings)
    if not info or not info.get("alive"):
        try:
            pid_file(settings).unlink()
        except FileNotFoundError:
            pass
        return False
    p = psutil.Process(int(info["pid"]))
    p.terminate()
    try:
        p.wait(timeout=timeout)
    except psutil.TimeoutExpired:
        p.kill()
        p.wait(timeout=5)
    pid_file(settings).unlink(missing_ok=True)
    _store_changed("OpenBao stopped (it restarts sealed)", "stopped")
    return True
