"""No AI attribution on code hosts (owner rule 2026-10-26; AGENTS.md invariant 11).

DLY AEOS writes to GitHub (PERSONAL), Bitbucket and the company's Jira/Confluence (OFFICE) with the owner's own
identity only. No AI may appear there as author, committer, co-author or contributor, nor in any attribution
line. Provenance (run id, agent, route, model) stays inside DLY AEOS records (EvidenceArtifact, run rows).

``find_ai_attribution`` looks for ATTRIBUTION, not for mentions of AI tools:

* attribution trailers (``Co-Authored-By:``, ``Assisted-By:``, ``Generated-By:``, ``Signed-off-by:``, ...) whose
  value names an AI tool, vendor or model, or a bot - anywhere in the text (a PR body line is copied into the
  squash commit);
* DLY AEOS provenance trailers (``AEOS-Agent:``, ``AEOS-Route:``, ``AEOS-Engine:``, ``AEOS-Model:``,
  ``AEOS-Prompt-Revision:``) anywhere, and generic provenance trailers (``Model:``, ``Route:``, ``Agent:``,
  ``Engine:``, ``LLM:``, ``Reviewer:``, ...) naming an AI in the trailer block (the last paragraph of
  ``Key: value`` lines, git's trailer convention);
* "Generated with/by <AI>" style statements: generated/created/written/authored/assisted/produced/drafted/made/
  coded/composed/reviewed/powered/crafted + with/by/using/via/through + an AI name, "with the help of <AI>",
  "AI-generated", "Claude-assisted";
* the robot emoji (U+1F916, ``:robot:``);
* AI vendor and bot e-mail addresses (``noreply@anthropic.com``, ``<id>+Copilot@users.noreply.github.com``,
  ``...[bot]@users.noreply.github.com``).

Ordinary text is not flagged: ``fix(claude_bridge): ...`` names a module (an AI name glued to ``_`` or ``.`` is an
identifier), "the claude binary path is configurable" or "route deepseek requests through the broker" describe the
system. A trailer naming a human called Claude is flagged (fail closed; the owner rewords it).

``assert_no_ai_attribution`` refuses (``PolicyDenied``), it never strips: the owner removes the attribution and
the text is sent again. Pure functions: no I/O, no database.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from aeos.core.errors import PolicyDenied

# AI names that are attribution whenever a statement says the text/change was produced "with/by" them.
_STRONG = (r"claude|anthropic|openai|chat[\s-]?gpt|gpt(?:-?\d[\w.]*)?|gemini|copilot|deepseek|qwen[\w.]*"
           r"|openrouter|opencode|codex|llama[\w.]*|mistral|mixtral|perplexity|grok|kimi[\s-]?(?:k\d[\w.]*|chat|ai)"
           r"|aider|windsurf|codeium|tabnine|coderabbit|cursor[\s-](?:ai|agent|ide|editor)")
# Generic AI wording ("generated by AI", "with the help of a language model").
_GENERIC = (r"(?:an?\s+)?(?:ai|a\.i\.|llms?|large\s+language\s+models?|language\s+models?|chat\s?bots?"
            r"|ai\s+(?:assistant|model|agent|tool|pair\s+programmer)s?|coding\s+(?:assistant|agent)s?)")
# Names that only count inside an attribution trailer or an identity (too ambiguous in prose: a cursor is
# also a database cursor, a sonnet a poem).
_WEAK = r"cursor|cursoragent|sonnet|opus|haiku|glm[\w.-]*|bard|amazon\s+q|replit\s+agent|lovable|bolt\.new"
_VENDOR_PREFIX = r"(?:(?:github|google|microsoft|amazon|aws|meta|alibaba|openai|anthropic|xai|x\.ai|mistral)\s+)?"
# A technical noun after the AI name makes it a component, not an author ("created by the claude bridge").
_COMPONENT = (r"(?!\s*[-_]?(?:bridge|binary|binaries|cli|process(?:es)?|sessions?|api|sdk|adapter|provider|config"
              r"|configuration|routes?|catalog|endpoint|integration|module|package|plugin|extension|tests?|fixture"
              r"|stub|fake|mock|support|token|tokens|keys?|pricing|quota|login|subscription|home|path)\b)")

_TERM_B = r"(?<![\w.])"  # an AI name glued to a word char or "." (aeos.claude_bridge) is an identifier
_TERM_E = r"(?![\w])"

_ANY_AI = re.compile(_TERM_B + rf"(?:{_STRONG}|{_WEAK})" + _TERM_E, re.I)
_BOT = re.compile(r"\[bot\]|(?<![\w-])bot(?![\w-])|(?<![\w])[\w]+-bot(?![\w])"
                  r"|\b(?:dependabot|renovate(?:bot)?|mergify|github-actions|greenkeeper|imgbot|allcontributors)\b",
                  re.I)

_VERBS = (r"generated|created|written|authored|co-?authored|co-?written|assisted|produced|drafted|made|coded"
          r"|composed|reviewed|powered|crafted")
_LEAD = r"[\[(`*_\"']*"
_PHRASE = re.compile(
    rf"\b(?:{_VERBS})(?:\s+\w+ly)?\s+(?:with|by|using|via|through|in|from|on)\s+"
    rf"(?:(?:the\s+)?(?:help|assistance|aid|support)\s+(?:of|from)\s+)?{_LEAD}{_VENDOR_PREFIX}"
    rf"{_TERM_B}(?:{_STRONG}|{_GENERIC}){_TERM_E}{_COMPONENT}", re.I)
_HELP = re.compile(
    rf"\bwith\s+(?:the\s+)?(?:help|assistance)\s+(?:of|from)\s+{_LEAD}{_VENDOR_PREFIX}"
    rf"{_TERM_B}(?:{_STRONG}|{_GENERIC}){_TERM_E}{_COMPONENT}", re.I)
# (as a trailer key - "AI-Assisted: ..." - the trailer rule decides, so "AI-Assisted: no" is not attribution)
_NOUN = re.compile(rf"{_TERM_B}(?:ai|llm|{_STRONG})[\s-](?:generated|assisted|written|authored|created|produced"
                   rf"|drafted){_TERM_E}(?![ \t*]*:)", re.I)
_ROBOT = re.compile("\U0001F916|:robot(?:_face)?:")

_ATTR_KEYS = (r"co-?authored-?by|co-?developed-?by|co-?written-?by|assisted-?by|generated-?(?:by|with)"
              r"|created-?(?:by|with)|authored-?by|written-?(?:by|with)|made-?(?:by|with)|built-?with|powered-?by"
              r"|helped-?by|signed-?off-?by|reviewed-?by|suggested-?by|tested-?by|acked-?by|reported-?by")
_AI_KEYS = r"ai-?(?:assisted|generated|written|authored|model|tool|agent)"
_LINE_PREFIX = r"^[ \t>*+-]*"
_ATTR_TRAILER = re.compile(rf"(?im){_LINE_PREFIX}(?:{_ATTR_KEYS})[ \t*]*:[ \t]*(?P<value>.*)$")
_AI_TRAILER = re.compile(rf"(?im){_LINE_PREFIX}(?:{_AI_KEYS})[ \t*]*:[ \t]*(?P<value>.*)$")
_AEOS_TRAILER = re.compile(
    rf"(?im){_LINE_PREFIX}aeos-(?:agent|route|engine|model|prompt-revision|supervisor|reviewer|worker)[ \t*]*:")
_GENERIC_KEYS = (r"models?|routes?|agents?|engines?|llms?|assistant|tool|generator|supervisor|reviewer|worker"
                 r"|x-ai-[\w-]+|x-model|x-llm")
_GENERIC_TRAILER = re.compile(rf"(?i)^[ \t>*+-]*(?:{_GENERIC_KEYS})[ \t*]*:[ \t]*(?P<value>.*)$")
_TRAILER_TOKEN = re.compile(r"^[A-Za-z0-9][A-Za-z0-9-]*[ \t]*:[ \t]?\S")

_EMAIL = re.compile(r"(?<![\w.+\[\]-])[A-Za-z0-9._%+\[\]-]{1,80}@[A-Za-z0-9-]{1,63}(?:\.[A-Za-z0-9-]{1,63})*"
                    r"\.[A-Za-z]{2,24}\b")
AI_VENDOR_DOMAINS = (
    "anthropic.com", "claude.ai", "claude.com", "openai.com", "chatgpt.com", "cursor.sh", "cursor.com",
    "anysphere.co", "codeium.com", "windsurf.com", "deepseek.com", "openrouter.ai", "opencode.ai", "aider.chat",
    "cognition.ai", "devin.ai", "tabnine.com", "mistral.ai", "x.ai", "perplexity.ai", "together.ai", "groq.com",
    "cohere.com", "cohere.ai", "moonshot.cn", "moonshot.ai", "zhipuai.cn", "z.ai", "qwenlm.ai", "githubcopilot.com",
    "coderabbit.ai", "sweep.dev", "deepmind.com", "lovable.dev", "replit.ai",
)
_AI_LOCAL_TOKENS = frozenset({
    "claude", "anthropic", "openai", "chatgpt", "gpt", "gemini", "copilot", "deepseek", "qwen", "openrouter",
    "opencode", "codex", "cursor", "cursoragent", "aider", "windsurf", "codeium", "tabnine", "coderabbit", "llama",
    "mistral", "grok", "bot", "dependabot", "renovate", "renovatebot", "mergify",
})

LABELS = {
    "AI_TRAILER": "attribution trailer naming an AI or a bot",
    "PROVENANCE_TRAILER": "provenance trailer naming the agent/route/model/engine",
    "GENERATED_WITH_AI": "statement that an AI produced it",
    "ROBOT_EMOJI": "robot emoji attribution",
    "AI_VENDOR_ADDRESS": "AI vendor or bot e-mail address",
}


@dataclass(frozen=True)
class AttributionFinding:
    code: str  # a key of LABELS
    line: int  # 1-based
    excerpt: str  # the offending line, shortened, personal data minimised

    def describe(self) -> str:
        return f"line {self.line}: {LABELS.get(self.code, self.code)} ({self.excerpt!r})"

    def as_dict(self) -> dict[str, object]:
        return {"code": self.code, "line": self.line, "excerpt": self.excerpt, "label": LABELS.get(self.code, "")}


def is_ai_address(email: str) -> bool:
    """True for an AI vendor or bot address (``noreply@anthropic.com``, ``123+Copilot@users.noreply.github.com``,
    ``x[bot]@users.noreply.github.com``). An ordinary personal or company address is never one."""
    text = (email or "").strip().strip("<>").lower()
    if "@" not in text:
        return False
    local, _, domain = text.rpartition("@")
    if any(domain == d or domain.endswith("." + d) for d in AI_VENDOR_DOMAINS):
        return True
    if "[bot]" in local:
        return True
    return any(tok in _AI_LOCAL_TOKENS for tok in re.split(r"[^a-z0-9]+", local) if tok)


def names_ai(text: str) -> bool:
    """True when *text* (an identity name or a trailer value) names an AI tool/vendor/model or a bot."""
    value = text or ""
    if _ANY_AI.search(value) or _BOT.search(value):
        return True
    return any(is_ai_address(m.group(0)) for m in _EMAIL.finditer(value))


def ai_identity_problem(name: str | None, email: str | None) -> str | None:
    """Why ``name <email>`` may not author or commit anything on a code host (None = no AI/bot in it)."""
    if email and is_ai_address(email):
        return "the e-mail is an AI vendor or bot address"
    if name and (_ANY_AI.search(name) or _BOT.search(name)):
        return "the name names an AI tool, vendor, model or a bot"
    return None


def _excerpt(line: str) -> str:
    from aeos.core.pii import redact_pii
    from aeos.core.redaction import redact_text

    text = redact_text(redact_pii(line.strip()))
    return text if len(text) <= 120 else text[:117] + "..."


def _trailer_block(lines: list[str]) -> range:
    """Line indexes of the trailer block: the last paragraph - never the first one (a subject such as
    ``docs: ...`` is not a trailer, as in git) - when every line in it is ``Token: value`` (or a folded
    continuation line). Empty range when the last paragraph is ordinary text."""
    end = len(lines)
    while end and not lines[end - 1].strip():
        end -= 1
    start = end
    while start and lines[start - 1].strip():
        start -= 1
    block = lines[start:end]
    first_paragraph = not any(ln.strip() for ln in lines[:start])
    if first_paragraph or not block or not _TRAILER_TOKEN.match(block[0]):
        return range(0)
    if all(_TRAILER_TOKEN.match(ln) or ln[:1] in (" ", "\t") for ln in block):
        return range(start, end)
    return range(0)


def find_ai_attribution(text: str | None) -> list[AttributionFinding]:
    """Every AI attribution in *text* (empty list = none), ordered by line."""
    if not text:
        return []
    lines = [ln.rstrip("\r") for ln in text.split("\n")]  # the regexes below are "\n"-anchored too
    found: dict[tuple[int, str], AttributionFinding] = {}

    def add(code: str, index: int) -> None:
        if 0 <= index < len(lines) and (index, code) not in found:
            found[(index, code)] = AttributionFinding(code, index + 1, _excerpt(lines[index]))

    def line_of(pos: int) -> int:
        return text.count("\n", 0, pos)

    for m in _ATTR_TRAILER.finditer(text):
        if names_ai(m.group("value")):
            add("AI_TRAILER", line_of(m.start()))
    for m in _AI_TRAILER.finditer(text):
        if m.group("value").strip().lower() not in ("no", "none", "false", "n/a", "0"):
            add("AI_TRAILER", line_of(m.start()))
    for m in _AEOS_TRAILER.finditer(text):
        add("PROVENANCE_TRAILER", line_of(m.start()))
    for i in _trailer_block(lines):
        generic = _GENERIC_TRAILER.match(lines[i])
        if generic and names_ai(generic.group("value")):
            add("PROVENANCE_TRAILER", i)
    for rx in (_PHRASE, _HELP, _NOUN):
        for m in rx.finditer(text):
            add("GENERATED_WITH_AI", line_of(m.start()))
    for m in _ROBOT.finditer(text):
        add("ROBOT_EMOJI", line_of(m.start()))
    for m in _EMAIL.finditer(text):
        if is_ai_address(m.group(0)):
            add("AI_VENDOR_ADDRESS", line_of(m.start()))
    return sorted(found.values(), key=lambda f: (f.line, f.code))


def assert_no_ai_attribution(text: str | None, where: str, *, code: str = "AI_ATTRIBUTION_IN_TEXT") -> None:
    """Refuse (``PolicyDenied``) text bound for a code host or the company's Atlassian systems when it carries AI
    attribution. Nothing is stripped: the message says what was found so the owner can remove it."""
    findings = find_ai_attribution(text)
    if not findings:
        return
    raise PolicyDenied(refusal_message(where, findings), code=code,
                       details={"where": where, "findings": [f.as_dict() for f in findings[:10]]})


def refusal_message(where: str, findings: list[AttributionFinding]) -> str:
    first = "; ".join(f.describe() for f in findings[:3])
    more = f" (+{len(findings) - 3} more)" if len(findings) > 3 else ""
    return (f"{where} refused: it carries AI attribution - {first}{more}. No AI may appear on GitHub, Bitbucket or "
            "the company's Atlassian systems (owner rule, AGENTS.md invariant 11): remove the attribution and send "
            "it again; provenance (run, agent, route, model) stays in DLY AEOS records")
