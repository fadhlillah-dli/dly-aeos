"""Generate docs/OWNER_TARGET_CAPABILITY_MATRIX.md (master §49 M0 "owner/target/capability matrix").

Built only from code: Readiness Doctor capability rules (aeos.doctor.capabilities), the domain
publication/target vocabulary (aeos.portfolio.providers) and the decision catalog (aeos.policy.catalog).
``tests/unit/test_owner_matrix.py`` fails when the committed file is out of date.

Usage: python scripts/owner_matrix.py [--check]
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
OUT = ROOT / "docs" / "OWNER_TARGET_CAPABILITY_MATRIX.md"


def render() -> str:
    from aeos.doctor.capabilities import HUMAN_ONLY, RULES
    from aeos.policy import catalog
    from aeos.portfolio import providers as pv

    lines = [
        "# Owner / target / capability matrix",
        "",
        "Generated by `scripts/owner_matrix.py` from the code (do not edit by hand). Master §49 M0, §20",
        "OWN/AUTH/CAP/ENF, §04 domain profiles, §08 capability gates.",
        "",
        "* **Owner** is always the human SUPER_ADMIN of the domain (OFFICE additionally needs a recorded",
        "  company authorisation, §23). No agent or model output is ever an owner or an authority.",
        "* A capability is READY only from Readiness Doctor evidence; this table states what *can* be",
        "  authorised, not that it is ready.",
        "",
        "## Capabilities (Readiness Doctor gates)",
        "",
        "| Capability | Domain | Owner / authority | Office gate | What it covers |",
        "|---|---|---|---|---|",
    ]
    for cap, rule in RULES.items():
        domain = rule.domain or "platform"
        authority = "SUPER_ADMIN of the domain" + (" + company authorisation (POLICY decision)" if rule.office_gate
                                                   else "")
        lines.append(f"| `{cap.value}` | {domain} | {authority} | {'yes' if rule.office_gate else 'no'} | "
                     f"{rule.label}: {rule.description} |")
    lines += ["", "## Targets per domain (exact identifiers an approval binds)", "",
              "| Domain | Purpose | Provider | Exact target identifier | Write authority |", "|---|---|---|---|---|"]
    for domain, purposes in pv.PUBLICATION_PROVIDER.items():
        for purpose, provider in purposes.items():
            ident = pv.ROOT_ID_NAMES.get(provider, "-")
            lines.append(f"| {domain} | {purpose} | {pv.LABELS.get(provider, provider)} | `{ident}` | "
                         "PUBLICATION decision bound to version + hash + preview (ADR-0074) |")
    lines += ["", "## Decision kinds (AUTH, §20)", "",
              "| Kind | Recorded by | Through the generic decision endpoint |", "|---|---|---|"]
    for kind in sorted(catalog.DECISION_KINDS):
        who = "human, or owner-recorded via ADR" if kind in catalog.OWNER_RECORDED_KINDS else "human SUPER_ADMIN"
        lines.append(f"| `{kind}` | {who} | {'yes' if kind in catalog.GENERIC_DECISION_KINDS else 'no'} |")
    lines += ["", "## Never delegated (human-only actions)", ""]
    lines += [f"* {h}" for h in HUMAN_ONLY]
    lines += ["", "Human-only operations no decision can delegate: "
              + ", ".join(f"`{o}`" for o in sorted(catalog.HUMAN_ONLY_OPERATIONS)) + ".", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is out of date; run: python scripts/owner_matrix.py")
            return 1
        print("owner matrix up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
