"""Owner rule 2026-10-26 (AGENTS.md invariant 11): nothing with AI attribution is written to GitHub Issues or to
the company's Jira/Confluence. The publisher adapters refuse it BEFORE any request (``ProviderBlocked``
AI_ATTRIBUTION_IN_TEXT -> the outbox operation is FAILED with the reason), never strip it; ordinary text passes."""

from __future__ import annotations

import httpx
import pytest
import respx

from aeos.publisher.providers import atlassian as atl
from aeos.publisher.providers import github_issues as gh
from aeos.publisher.providers.base import OpContext, ProviderBlocked

BASE = "https://contoh.atlassian.net"
CFG = atl.AtlassianConfig(base_url=BASE, enabled=True, deployment="CLOUD", space_id="SP1", parent_id="PARENT",
                          project_key="ABC")
AUTH = "Basic dGVzdDp0ZXN0"
FOOTER = "\n\n\U0001F916 Generated with [Claude Code](https://claude.com/claude-code)"


def _ctx(**kw) -> OpContext:
    base = dict(operation_id="op", publication_id="pub", project_id="proj", project_key="k", project_name="Contoh",
                domain="PERSONAL", provider="github-issues", operation="create_issue", logical_id="issue:task:T1",
                idempotency_key="sha256:" + "2" * 64, title="T1", target={},
                payload={"title": "[k] T1", "body": "Tujuan", "labels": ["aeos"]})
    base.update(kw)
    return OpContext(**base)


def _gh() -> gh.GitHubIssuesProvider:
    return gh.GitHubIssuesProvider(repo="owner/contoh", client=httpx.Client(), token="ghp_unit0123456789abcdefghijklmnopq")


def _refused(fn) -> ProviderBlocked:
    with respx.mock(assert_all_mocked=True) as mock:
        with pytest.raises(ProviderBlocked) as e:
            fn()
        assert not mock.calls, "nothing is sent"
    assert e.value.code == "AI_ATTRIBUTION_IN_TEXT" and "aturan owner" in e.value.remedy
    return e.value


@pytest.mark.parametrize(("field", "payload"), [
    ("body", {"title": "[k] T1", "body": "Tujuan" + FOOTER}),
    ("body", {"title": "[k] T1", "body": "Tujuan\n\nCo-Authored-By: Claude <noreply@anthropic.com>"}),
    ("title", {"title": "[k] T1 (generated by ChatGPT)", "body": "Tujuan"}),
])
def test_github_issue_with_ai_attribution_is_refused_before_the_request(field, payload):
    err = _refused(lambda: _gh().execute(_ctx(payload=payload)))
    assert err.details["field"] == field and "GitHub issue" in err.message


def test_github_issue_about_the_claude_bridge_module_is_published():
    with respx.mock(assert_all_mocked=True) as mock:
        route = mock.post(f"{gh.GITHUB_API}/repos/owner/contoh/issues").mock(return_value=httpx.Response(201, json={
            "number": 3, "html_url": "https://github.com/owner/contoh/issues/3", "state": "open"}))
        res = _gh().execute(_ctx(payload={"title": "[k] fix(claude_bridge): validate argv",
                                          "body": "Route deepseek requests through the broker.", "labels": ["aeos"]}))
    assert res.external_id == "3" and route.called


def test_github_label_with_attribution_is_refused():
    _refused(lambda: _gh().execute(_ctx(operation="ensure_label", logical_id="label:x",
                                        payload={"name": "made-with-ai", "description": "Generated by Copilot"})))


def test_jira_issue_with_ai_attribution_is_refused_before_the_request():
    j = atl.JiraProvider(CFG, client=httpx.Client(), auth_header=AUTH)
    err = _refused(lambda: j.execute(_ctx(provider="jira", payload={"title": "T1", "body": "Tujuan" + FOOTER})))
    assert err.details["field"] == "description" and "Jira issue" in err.message


def _conf() -> atl.ConfluenceProvider:
    p = atl.ConfluenceProvider(CFG, client=httpx.Client(), auth_header=AUTH)
    p._caps = {"status": "READY", "reasons": []}  # capability probes are covered in test_publisher_atlassian
    return p


def test_confluence_page_and_folder_with_ai_attribution_are_refused():
    page = _ctx(provider="confluence", operation="create_doc", logical_id="doc:prd", title="PRD",
                payload={"markdown": "# PRD\n\nIsi." + FOOTER})
    err = _refused(lambda: _conf().execute(page))
    assert err.details["field"] == "body" and "Confluence page" in err.message
    folder = _ctx(provider="confluence", operation="create_folder", logical_id="root", title="Written by Claude")
    _refused(lambda: _conf().execute(folder))


def test_confluence_page_update_with_ai_attribution_is_refused_before_the_put():
    """An update re-reads the page (read-only) and refuses the new body - including any HUMAN_GOVERNED text kept from
    the page - before the PUT: nothing is written, nothing is stripped."""
    with respx.mock(assert_all_mocked=True, assert_all_called=False) as mock:
        mock.get(f"{BASE}/wiki/api/v2/pages/P1").mock(return_value=httpx.Response(200, json={
            "id": "P1", "version": {"number": 3}, "body": {"storage": {"value": "<p>lama</p>"}}}))
        put = mock.put(f"{BASE}/wiki/api/v2/pages/P1").mock(return_value=httpx.Response(200, json={
            "id": "P1", "version": {"number": 4}}))
        with pytest.raises(ProviderBlocked) as e:
            _conf().execute(_ctx(provider="confluence", operation="update_doc", logical_id="doc:prd", title="PRD",
                                 existing_external_id="P1", existing_revision="3",
                                 payload={"markdown": "# PRD\n\nIsi baru." + FOOTER}))
        assert not put.called
    assert e.value.code == "AI_ATTRIBUTION_IN_TEXT" and e.value.details["field"] == "body"
