@pytest.mark.parametrize("text", [
    "fix: y\n\nCo-Authored-By: C\u200blaude <owner@example.com>",  # zero-width space inside the name
    "fix: y\n\nCo-Authored-By: Cl\u00adaude <owner@example.com>",  # soft hyphen
    "fix: y\n\nCo-Authored-By: \uff23\uff4c\uff41\uff55\uff44\uff45 <owner@example.com>",  # fullwidth letters
    "fix: y\n\nCo-Authored-By: \u0421l\u0430ude <owner@example.com>",  # Cyrillic look-alike letters
])
def test_obfuscated_ai_names_are_still_caught(text):
    """What the code host shows is "Claude": invisible characters, fullwidth forms and look-alike letters are folded
    before matching (the text itself is never changed)."""
    assert "AI_TRAILER" in codes(text)
    assert is_ai_address("noreply@\u0430nthropic.com")


