"""Owner rule 2026-10-26 (AGENTS.md invariant 11): no AI may appear on GitHub, Bitbucket or the company's
Atlassian systems - not as author, committer, co-author or contributor, and not in any attribution line.

``aeos.core.attribution`` is the one shared guard for every outbound text. It must catch each attribution pattern
and must NOT flag ordinary text about the system (a commit subject about the ``claude_bridge`` module is a module
name, not attribution). Vendor addresses below are the public noreply addresses AI tools write; no personal
address appears in this file (the repository is public)."""

from __future__ import annotations

import pytest

from aeos.core.attribution import (
    ai_identity_problem,
    assert_no_ai_attribution,
    find_ai_attribution,
    is_ai_address,
)
from aeos.core.errors import PolicyDenied


def codes(text: str) -> set[str]:
    return {f.code for f in find_ai_attribution(text)}


