def test_findings_name_the_line_and_minimise_personal_data():
    text = "feat: x\n\nbody\n\nCo-Authored-By: Claude <owner.private@example.com>"
    (f,) = find_ai_attribution(text)
    assert f.line == 5 and f.code == "AI_TRAILER"
    assert "owner.private@example.com" not in f.excerpt and "[PII:EMAIL]" in f.excerpt
    assert "line 5" in f.describe()


def test_assert_refuses_and_never_strips():
    body = "Adds login.\n\n\U0001F916 Generated with [Claude Code](https://claude.com/claude-code)"
    with pytest.raises(PolicyDenied) as e:
        assert_no_ai_attribution(body, "GitHub pull request body")
    assert e.value.code == "AI_ATTRIBUTION_IN_TEXT"
    assert "GitHub pull request body refused" in e.value.message and "remove the attribution" in e.value.message
    assert {f["code"] for f in e.value.details["findings"]} == {"GENERATED_WITH_AI", "ROBOT_EMOJI"}
    assert body.endswith("claude-code)")  # the caller's text is untouched
    assert_no_ai_attribution("fix(claude_bridge): argv", "commit message")  # no raise
    with pytest.raises(PolicyDenied) as e2:
        assert_no_ai_attribution("x\n\nCo-Authored-By: Claude", "commit", code="AI_ATTRIBUTION_IN_COMMIT")
    assert e2.value.code == "AI_ATTRIBUTION_IN_COMMIT"


